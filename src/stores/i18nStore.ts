const STORAGE_KEY = 'isocraft_locale'

export function translateSingle(
  locale: SupportedLocale,
  rawKey: string,
  params?: Record<string, string | number>
): string {
  const localeDict = translations[locale] as Record<string, string> | undefined
  const enDict = translations.en as Record<string, string>

  // 1. Direct lookup
  let text = localeDict?.[rawKey] ?? enDict[rawKey]

  // 2. Fallback to common.<rawKey> if not found and rawKey does not contain '.'
  if (!text && !rawKey.includes('.')) {
    const commonKey = `common.${rawKey}`
    text = localeDict?.[commonKey] ?? enDict[commonKey]
  }

  // 3. Fallback to rawKey
  if (!text) {
    text = rawKey
  }

  // Parameter replacement
  if (params) {
    const safeParams: Record<string, string | number> = { ...params }
    if (safeParams.num !== undefined && safeParams.number === undefined) {
      safeParams.number = safeParams.num
    } else if (safeParams.number !== undefined && safeParams.num === undefined) {
      safeParams.num = safeParams.number
    }
    for (const [k, v] of Object.entries(safeParams)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
    }
  }

  return text
}

export const useI18nStore = defineStore('i18n', () => {
  const currentLocale = ref<SupportedLocale>(
    (localStorage.getItem(STORAGE_KEY) as SupportedLocale) || 'en'
  )

  const activeLocale = computed(() => currentLocale.value)

  function setLocale(locale: SupportedLocale) {
    if (locale in translations) {
      currentLocale.value = locale
      localStorage.setItem(STORAGE_KEY, locale)
      document.documentElement.lang = locale
    }
  }

  /**
   * Unified translation function:
   * - Single key with params: t('common.tileCount', { count: 5 })
   * - Direct key: t('common.save')
   * - Short key: t('save') -> auto-resolves to 'common.save'
   * - Composite phrases: t('select', 'room') -> "Select Room" / "Xonani tanlash" / "Выбрать комнату"
   */
  function t(...args: any[]): string {
    if (args.length === 0) return ''

    // Case 1: single key with optional params: t('key', { count: 5 })
    if (args.length === 2 && typeof args[1] === 'object' && args[1] !== null && !Array.isArray(args[1])) {
      return translateSingle(currentLocale.value, String(args[0]), args[1])
    }

    // Case 2: multiple string keys: t('select', 'room') or t('create', 'room')
    const pieces: string[] = []
    for (const arg of args) {
      if (typeof arg === 'string') {
        pieces.push(translateSingle(currentLocale.value, arg))
      }
    }
    return pieces.join(' ')
  }

  return {
    currentLocale,
    activeLocale,
    locales: SUPPORTED_LOCALES,
    setLocale,
    t
  }
})

export function useI18n() {
  const store = useI18nStore()
  return {
    t: (...args: any[]) => store.t(...args),
    currentLocale: computed(() => store.currentLocale),
    setLocale: store.setLocale,
    locales: store.locales,
    store
  }
}
