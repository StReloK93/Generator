const STORAGE_KEY = 'isocraft_locale'

export const useI18nStore = defineStore('i18n', () => {
  const currentLocale = ref<SupportedLocale>(
    (localStorage.getItem(STORAGE_KEY) as SupportedLocale) || 'en'
  )

  const activeLocale = computed(() => currentLocale.value)

  function setLocale(locale: SupportedLocale) {
    if (locale in translations) {
      currentLocale.value = locale
      localStorage.setItem(STORAGE_KEY, locale)
      document.documentElement.lang = locale
    }
  }

  function t(key: string, params?: Record<string, string | number>): string {
    const localeDict = translations[currentLocale.value] as Record<string, string> | undefined
    const enDict = translations.en as Record<string, string>

    let text = localeDict?.[key] ?? enDict[key] ?? key

    if (params) {
      const safeParams: Record<string, string | number> = { ...params }
      if (safeParams.num !== undefined && safeParams.number === undefined) {
        safeParams.number = safeParams.num
      } else if (safeParams.number !== undefined && safeParams.num === undefined) {
        safeParams.num = safeParams.number
      }
      for (const [k, v] of Object.entries(safeParams)) {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
      }
    }

    return text
  }

  return {
    currentLocale,
    activeLocale,
    locales: SUPPORTED_LOCALES,
    setLocale,
    t
  }
})

export function useI18n() {
  const store = useI18nStore()
  return {
    t: (key: string, params?: Record<string, string | number>) => store.t(key, params),
    currentLocale: computed(() => store.currentLocale),
    setLocale: store.setLocale,
    locales: store.locales,
    store
  }
}
